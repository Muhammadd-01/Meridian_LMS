import { Download, FileText, FileArchive, FileSpreadsheet, Ban } from 'lucide-react'
import { getAllLessons } from '../../utils/learning'
import { formatMinutes } from '../../utils/format'

function download(filename, content, type = 'text/plain') {
  const url = URL.createObjectURL(new Blob([content], { type: `${type};charset=utf-8` }))
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

/** Course resources: two files generated in the browser plus clearly labelled demo placeholders. */
export default function ResourceList({ course, notes, onDownloaded }) {
  const syllabus = () => {
    const lines = [`${course.title}`, `${course.providerName} · ${course.difficulty} · approx. ${course.durationHours} hours`, '', course.description, '', 'CURRICULUM']
    course.modules.forEach((m, i) => {
      lines.push('', `Module ${i + 1}: ${m.title}`)
      m.lessons.forEach((l) => lines.push(`  - ${l.title} (${l.type}${l.durationMinutes ? `, ${formatMinutes(l.durationMinutes)}` : ''})`))
    })
    lines.push('', 'Generated by Meridian LMS (demo).')
    download(`${course.slug}-syllabus.txt`, lines.join('\n'))
    onDownloaded?.('Syllabus downloaded.')
  }

  const exportNotes = () => {
    const lessons = getAllLessons(course)
    const body = notes.length
      ? notes.map((n) => `## ${lessons.find((l) => l.id === n.lessonId)?.title || 'Lesson'}\n\n${n.text}\n`).join('\n')
      : '_No notes yet._'
    download(`${course.slug}-my-notes.md`, `# My notes — ${course.title}\n\n${body}`, 'text/markdown')
    onDownloaded?.('Your notes were exported.')
  }

  const items = [
    { name: 'Course syllabus', meta: 'TXT · generated from the curriculum', icon: FileText, action: syllabus },
    { name: 'My notes for this course', meta: `Markdown · ${notes.length} note${notes.length === 1 ? '' : 's'}`, icon: FileText, action: exportNotes },
    { name: 'Starter project templates', meta: 'ZIP · demo resource', icon: FileArchive },
    { name: 'Practice dataset / worksheet', meta: 'XLSX · demo resource', icon: FileSpreadsheet },
  ]

  return (
    <ul className="divide-y divide-line rounded-2xl border border-line bg-white">
      {items.map((item) => (
        <li key={item.name} className="flex items-center gap-4 p-4">
          <span className="flex h-10 w-10 shrink-0 items-center justify-center rounded-lg bg-primary-soft text-primary"><item.icon className="h-5 w-5" aria-hidden="true" /></span>
          <div className="min-w-0 flex-1">
            <p className="text-sm font-medium text-ink">{item.name}</p>
            <p className="text-xs text-muted">{item.meta}</p>
          </div>
          {item.action ? (
            <button type="button" className="btn btn-secondary btn-sm" onClick={item.action}><Download className="h-4 w-4" aria-hidden="true" />Download</button>
          ) : (
            <span className="inline-flex items-center gap-1 text-xs font-medium text-muted" title="This file is not included in the frontend demo"><Ban className="h-3.5 w-3.5" aria-hidden="true" />Demo resource — not included</span>
          )}
        </li>
      ))}
    </ul>
  )
}
